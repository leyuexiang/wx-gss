## 5. 后期处理优化

### 5.1 自动清理杂点

**工具脚本**：`/home/3dgs/scripts/post_process.py`

**使用方法**：
```bash
# 基础清理
python post_process.py input.ply output.ply

# 自定义阈值
python post_process.py input.ply output.ply \
  --opacity 0.15 \    # 不透明度阈值（0.1-0.3）
  --distance 95       # 距离百分位（90-98）
```

**参数调优**：

| 参数 | 范围 | 效果 | 适用场景 |
|------|------|------|----------|
| `--opacity 0.05` | 保守 | 删除极少点 | 担心误删 |
| `--opacity 0.10` | 标准 | 删除透明杂点 | 日常使用 ⭐ |
| `--opacity 0.15` | 激进 | 删除更多杂点 | 杂点很多 |
| `--opacity 0.20` | 极端 | 可能误删细节 | 慎用 |

| 参数 | 范围 | 效果 | 适用场景 |
|------|------|------|----------|
| `--distance 98` | 保守 | 仅删除极远点 | 物体完整 |
| `--distance 95` | 标准 | 删除周围杂点 | 日常使用 ⭐ |
| `--distance 90` | 激进 | 删除更多外围点 | 背景杂乱 |
| `--distance 85` | 极端 | 可能误删边缘 | 慎用 |

**效果预期**：
- 删除点数：5-15%
- 文件大小：减少 5-15%
- 视觉效果：杂点明显减少

