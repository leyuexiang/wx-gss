## 1. 问题诊断

### 1.1 常见质量问题

| 问题 | 表现 | 根本原因 |
|------|------|----------|
| **模糊不清晰** | 细节丢失，边缘模糊 | 降采样过大、迭代不足、图片分辨率低 |
| **周围杂点** | 漂浮的高斯点、背景噪声 | 背景复杂、拍摄角度不足、训练过度 |
| **几何扭曲** | 物体变形、位置错误 | 相机位姿估计不准、图片数量不足 |
| **颜色不准** | 色彩偏差、过曝/欠曝 | 光照不均、相机白平衡不一致 |
| **空洞缺失** | 物体表面有洞 | 视角覆盖不足、特征点匹配失败 |

### 1.2 问题定位流程

```
1. 检查训练统计 (train_stats.json)
   ├─ final_loss > 0.05 → 训练不足或数据质量差
   ├─ num_gaussians < 100K → 重建失败或图片太少
   └─ peak_gpu_mem_gb > 7GB → 显存不足，被迫降质

2. 检查拍摄质量
   ├─ 图片数量 < 8 张 → 增加拍摄数量
   ├─ 背景复杂 → 使用纯色背景
   └─ 光照不均 → 改善拍摄环境

3. 检查模型表现
   ├─ 查看不同角度渲染效果
   ├─ 对比训练图片和渲染图片
   └─ 在 SuperSplat 中检查高斯分布
```

