## 4. 拍摄质量优化

### 4.1 拍摄环境准备

#### 背景处理 ⭐⭐⭐⭐⭐（最重要）

**问题**：复杂背景会产生大量杂点

**解决方案**：

1. **纯色背景布/纸**
   - 白色（推荐）：适合深色物体
   - 黑色：适合浅色物体
   - 灰色：通用选择
   - 绿幕：后期可抠图

2. **背景距离**
   - 物体离背景 > 50cm
   - 避免阴影投射到背景

3. **DIY 简易摄影棚**
   ```
   材料：
   - 白色泡沫板 × 3（背景 + 两侧反光）
   - LED 灯 × 2（均匀照明）
   - 转盘（可选，方便旋转拍摄）

   成本：< 100 元
   ```

---

#### 光照控制 ⭐⭐⭐⭐

**问题**：光照不均导致阴影、反光、色彩不一致

**解决方案**：

1. **三点布光法**
   ```
         主光源
           ↓
       [物体]
      ↗     ↖
   辅助光  补光板
   ```

2. **避免以下情况**
   - ❌ 单侧强光（产生强阴影）
   - ❌ 顶光直射（物体底部阴影）
   - ❌ 强反光材质（金属、玻璃需柔光）
   - ❌ 混合光源（自然光 + 室内灯，色温不一致）

3. **推荐配置**
   - 柔光箱或反光伞
   - 色温 5000-6500K（接近自然光）
   - 亮度均匀，无明显阴影

---

### 4.2 拍摄技巧

#### 图片数量与角度分布

**MASt3R 少视角场景**（2-15 张）：

| 图片数 | 覆盖策略 | 质量预期 |
|--------|----------|----------|
| **2-4张** | 正面 + 侧面 | 基础模型，可能有空洞 |
| **5-8张** | 环绕 180° | 良好，推荐 ⭐ |
| **8-12张** | 环绕 360° | 优秀，完整覆盖 ⭐⭐ |
| **12-15张** | 360° + 俯仰角 | 极致，细节丰富 |

**拍摄角度分布示例**（8 张图）：
```
俯视图：
        1
    8       2
  7           3
    6       4
        5

侧视图：（水平环绕，相机与物体等高）
1→2→3→4→5→6→7→8（每 45° 一张）
```

**关键点**：
- ✅ 相邻照片重叠 > 40%
- ✅ 环绕均匀分布
- ✅ 包含顶部/底部视角（如需要）
- ❌ 避免视角跳跃过大

---

#### 拍摄参数设置

**相机设置**（手机/单反）：

| 参数 | 设置 | 原因 |
|------|------|------|
| **焦距** | 固定（不要变焦） | MASt3R 假设共享内参 |
| **光圈** | F5.6 - F11 | 确保景深足够 |
| **ISO** | 100-400 | 降低噪点 |
| **快门** | > 1/60s | 避免运动模糊 |
| **白平衡** | 固定（如 5500K） | 保持色温一致 |
| **对焦** | 手动/锁定 | 避免焦点漂移 |
| **HDR** | 关闭 | 保持亮度一致 |

**手机拍摄技巧**：
- 使用专业模式（Pro Mode）
- 锁定曝光和对焦（长按屏幕）
- 使用三脚架或稳定器
- 关闭美颜和滤镜

---

#### 物体摆放

**尺寸比例**：
- 物体占画面：**60-75%** ⭐
- 留白边缘：15-20%
- 避免：太小（<40%）或太大（>90%）

**距离选择**：
- 小物体（< 20cm）：距离 30-50cm
- 中型物体（20-50cm）：距离 50-100cm
- 大型物体（> 50cm）：距离 100-200cm

**固定物体**：
- 使用转盘（旋转物体，固定相机）
- 或固定物体，旋转相机
- 确保物体不会移动或倾斜

