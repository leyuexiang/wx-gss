### 5.3 批量处理自动化

**场景**：需要处理大量模型

**脚本**：`/home/3dgs/scripts/batch_process.sh`

<function_calls>
<invoke name="Write">
<parameter name="content">#!/bin/bash
# 批量清理 PLY 文件

INPUT_DIR="$1"
OUTPUT_DIR="$2"
OPACITY="${3:-0.1}"
DISTANCE="${4:-95}"

if [ -z "$INPUT_DIR" ] || [ -z "$OUTPUT_DIR" ]; then
    echo "用法: $0 <输入目录> <输出目录> [不透明度阈值] [距离百分位]"
    exit 1
fi

mkdir -p "$OUTPUT_DIR"

for ply in "$INPUT_DIR"/*.ply; do
    filename=$(basename "$ply")
    echo "处理: $filename"
    python /home/3dgs/scripts/post_process.py \
        "$ply" \
        "$OUTPUT_DIR/$filename" \
        --opacity "$OPACITY" \
        --distance "$DISTANCE"
done

echo "批量处理完成！"
echo "输出目录: $OUTPUT_DIR"
