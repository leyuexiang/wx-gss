## 3. 训练参数优化

### 3.1 参数配置方案

#### 方案 A：快速预览（2 分钟）
```json
{
  "sfm_backend": "mast3r",
  "iterations": 2000,
  "downsample": 4,
  "cap_max": 300000
}
```
**适用场景**：快速验证拍摄质量、测试不同角度

**优点**：速度快、显存占用低（~1.5GB）
**缺点**：质量一般、细节不足

---

#### 方案 B：标准质量（3 分钟）⭐ 推荐
```json
{
  "sfm_backend": "mast3r",
  "iterations": 3000,
  "downsample": 2,
  "cap_max": 500000
}
```
**适用场景**：日常使用、平衡质量和速度

**优点**：质量较好、速度适中
**缺点**：细节略有损失

---

#### 方案 C：高质量（5 分钟）⭐⭐ 推荐高质量需求
```json
{
  "sfm_backend": "mast3r",
  "iterations": 5000,
  "downsample": 1,
  "cap_max": 800000
}
```
**适用场景**：展示、存档、高要求场景

**优点**：清晰度高、细节丰富
**缺点**：耗时较长、显存需求高（~5GB）

---

#### 方案 D：极致质量（8 分钟）
```json
{
  "sfm_backend": "mast3r",
  "iterations": 7000,
  "downsample": 1,
  "cap_max": 1000000
}
```
**适用场景**：专业级需求、大型物体

**优点**：极致清晰、最多细节
**缺点**：耗时长、显存需求高（~7GB）

---

### 3.2 参数调优指南

#### iterations（训练迭代次数）

| 值 | 收敛程度 | 训练时间 | 适用场景 |
|-----|---------|----------|----------|
| 1000-2000 | 欠拟合 | 快（~1分钟） | 快速预览 |
| 3000-5000 | 良好 | 中等（2-4分钟） | 日常使用 ⭐ |
| 7000+ | 充分 | 慢（5-8分钟） | 高质量需求 |

**调优建议**：
- 查看 `final_loss`：> 0.05 说明训练不足，增加 iterations
- 少视角场景（5-10张）：3000-5000 即可
- 密集拍摄（20+张）：建议 7000+

---

#### downsample（降采样倍数）

| 值 | 分辨率 | 显存占用 | 细节保留 | 适用场景 |
|----|--------|----------|----------|----------|
| 1 | 原始 | 高（~5GB） | 最佳 | 高质量需求 ⭐⭐ |
| 2 | 1/4像素 | 中（~3GB） | 良好 | 日常使用 ⭐ |
| 4 | 1/16像素 | 低（~1.5GB） | 一般 | 快速预览 |
| 8 | 1/64像素 | 极低（~1GB） | 较差 | 显存受限 |

**调优建议**：
- 原始图片 > 2000px：downsample=2 即可保持细节
- 原始图片 < 1000px：downsample=1 避免过度模糊
- 显存不足（CUDA OOM）：增大 downsample

---

#### cap_max（高斯数量上限）

| 值 | 效果 | 副作用 | 适用场景 |
|-----|------|--------|----------|
| 300K-500K | 简洁 | 细节可能不足 | 少视角（2-8张） ⭐ |
| 800K-1M | 平衡 | 可能有少量杂点 | 标准场景 ⭐ |
| 1M-1.5M | 丰富 | 杂点较多 | 复杂场景 |

**调优建议**：
- 杂点多：减小 cap_max（1M → 500K）
- 细节不足：增大 cap_max（500K → 1M）
- 少视角场景：建议 300K-500K（避免过拟合）

---

### 3.3 显存优化策略

**8GB 显存配置建议**（RTX 4060 / RTX 3070）：

| 图片数 | downsample | iterations | cap_max | 预计显存 |
|--------|-----------|-----------|---------|----------|
| 2-5张 | 1 | 5000 | 500K | ~3GB ✅ |
| 5-10张 | 1 | 5000 | 800K | ~5GB ✅ |
| 10-15张 | 2 | 5000 | 1M | ~4GB ✅ |
| 20+张 | 2 | 7000 | 1M | ~6GB ✅ |

**显存不足排查**：
```bash
# 查看训练统计中的显存峰值
cat train_stats.json | jq .peak_gpu_mem_gb

# 如果接近 8GB，按以下顺序调整：
# 1. downsample: 1 → 2 → 4
# 2. cap_max: 1M → 800K → 500K
# 3. iterations: 7000 → 5000 → 3000
```

